import assert from 'node:assert/strict';
import {baseColor, cloudBrightness, cloudCode, effectiveWeather, displayPhase, sampleDisplay} from '../src/lib/weather-engine.mjs';
const forecast={temperatures:[18,9,8.9999,-40],code:800,clouds:0,rainProbability:80,daytimeRain:true};
// Golden RGB values calculated from the supplied C++ HSV stops and PWM scale.
assert.deepEqual(baseColor(forecast,'temperature',0),[255,136,0]);
assert.deepEqual(baseColor(forecast,'temperature',1),[229,195,57]);
assert.deepEqual(baseColor(forecast,'temperature',2),[72,228,242]);
assert.deepEqual(baseColor(forecast,'temperature',3),[0,14,178]);
assert.equal(cloudBrightness(0),1);
assert.equal(cloudBrightness(50),.875);
assert.equal(cloudBrightness(100),.5);
assert.deepEqual(baseColor({...forecast,code:500,clouds:100},'weather'),[19,44,127]);
assert.equal(effectiveWeather({...forecast,code:500,rainProbability:59}),800);
assert.equal(effectiveWeather({...forecast,code:500,rainProbability:60}),500);
assert.equal(effectiveWeather({...forecast,code:300,clouds:90,daytimeRain:false}),804);
assert.equal(effectiveWeather({...forecast,code:200,rainProbability:0}),200);
assert.equal(cloudCode(15),800);assert.equal(cloudCode(16),801);assert.equal(cloudCode(85),804);
assert.equal(displayPhase(19999).label,'Temperature');
assert.equal(displayPhase(21000).amount,.5);
assert.equal(displayPhase(22000).label,'Weather');
assert.equal(displayPhase(30000).stage,1);
assert.equal(displayPhase(31000).label,'Weather → temperature');
assert.equal(displayPhase(60000).stage,2);
assert.equal(displayPhase(90000).stage,3);
assert.equal(displayPhase(120000).stage,0);
assert.deepEqual(sampleDisplay(forecast,10000,'temperature',0,false).rgb,[255,129,0]);
assert.deepEqual(sampleDisplay(forecast,0,'cycle',0,false).rgb,[0,0,0]);
assert.deepEqual(sampleDisplay(forecast,120750,'cycle',0,false).rgb,[0,0,0]);
console.log('PASS: firmware RGB reference values, 9°C boundary, cloud dimming, daytime rain filter, PWM scaling and display scheduling.');
